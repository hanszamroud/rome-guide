/* Service worker: stores every file of the app on the phone so it works without internet.
   The file list and version come from data/precache.js (generated by tools/build_data.py). */
importScripts("data/precache.js");
const CACHE = "rome-walk-" + self.PRECACHE_VERSION;

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // add one by one so a single missing file does not abort the whole install
    await Promise.all(self.PRECACHE_FILES.map((f) =>
      cache.add(new Request(f, { cache: "reload" })).catch((e) => console.warn("precache failed", f, e))));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok) cache.put(req, res.clone());
      return res;
    } catch (e) {
      if (req.mode === "navigate") return (await cache.match("index.html")) || Response.error();
      return Response.error();
    }
  })());
});

self.addEventListener("message", (event) => {
  if (!event.data || event.data.type !== "status") return;
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    let cached = 0;
    for (const f of self.PRECACHE_FILES) if (await cache.match(f, { ignoreSearch: true })) cached++;
    event.ports[0].postMessage({ cached, total: self.PRECACHE_FILES.length, version: self.PRECACHE_VERSION });
  })());
});
